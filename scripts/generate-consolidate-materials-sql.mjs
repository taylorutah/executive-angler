// Generate a single SQL migration file that consolidates exploded
// tying_materials rows. Output is safe to paste into the Supabase SQL editor.
//
// Strategy per cluster:
//   1. Pick survivor (prefer multi-color row, then highest popularity)
//   2. UPDATE survivor.colors = union of all extracted colors
//   3. UPDATE survivor.sizes  = union of all sizes (in case any varied)
//   4. UPDATE fly_recipe_ingredients to re-point material_id + pull
//      color/size from old row when the recipe didn't have one
//   5. UPDATE user_materials_inventory likewise
//   6. DELETE the non-survivor rows
//
// Cross-stem normalization: for THREAD, two stems that differ only by
// brand-prefix ("Veevus 10/0" vs "10/0") collapse to the same cluster
// when (brand, weight) match.

import { createClient } from '@supabase/supabase-js';
import { readFileSync, writeFileSync, mkdirSync } from 'fs';

try {
  const env = readFileSync('.env.local', 'utf8');
  for (const line of env.split('\n')) {
    const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
    if (m) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
} catch {}

const s = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
);

// Paginate all materials
const materials = [];
for (let offset = 0; ; offset += 1000) {
  const { data, error } = await s
    .from('tying_materials')
    .select('id, slug, name, brand, category, subcategory, sizes, colors, material_type, weight, finish, popularity, created_at')
    .order('id')
    .range(offset, offset + 999);
  if (error) throw error;
  if (!data?.length) break;
  materials.push(...data);
  if (data.length < 1000) break;
}
console.log(`Loaded ${materials.length} materials`);

function stripColorSuffix(name, color) {
  if (!name || !color) return name;
  const lower = name.toLowerCase();
  const c = color.toLowerCase().trim();
  if (lower.endsWith(c)) {
    return name.slice(0, name.length - c.length).trim().replace(/[-,\s]+$/, '');
  }
  return name;
}

// Normalize a thread stem so "Veevus 10/0" and "10/0" collapse together
// when the brand is the same. Drops a leading brand token if present.
function normalizeStem(stem, brand) {
  if (!brand) return stem;
  const b = brand.toLowerCase();
  const s = stem.toLowerCase();
  if (s.startsWith(b + ' ')) return stem.slice(brand.length + 1).trim();
  return stem;
}

const clusters = new Map();
for (const m of materials) {
  const colors = Array.isArray(m.colors) ? m.colors : [];
  const isExploded = colors.length === 1;
  const extractedColor = isExploded ? colors[0] : '';
  let stem = isExploded ? stripColorSuffix(m.name, extractedColor) : m.name;
  stem = normalizeStem(stem, m.brand);
  const key = [
    m.category || '',
    (m.brand || '').toLowerCase(),
    stem.toLowerCase(),
    (m.weight || '').toLowerCase(),
  ].join('||');
  if (!clusters.has(key)) clusters.set(key, []);
  clusters.get(key).push({ ...m, _stem: stem, _extractedColor: extractedColor, _isExploded: isExploded });
}

const dupClusters = [...clusters.entries()].filter(([, rows]) => rows.length > 1);
console.log(`Duplicate clusters: ${dupClusters.length}`);
console.log(`Rows to consolidate: ${dupClusters.reduce((sum, [, r]) => sum + r.length, 0)}`);

// Build SQL
const sqlLines = [];
sqlLines.push('-- Consolidate exploded tying_materials rows');
sqlLines.push('-- Generated by scripts/generate-consolidate-materials-sql.mjs');
sqlLines.push(`-- Source row count: ${materials.length}`);
sqlLines.push(`-- Clusters: ${dupClusters.length}`);
sqlLines.push('');
sqlLines.push('BEGIN;');
sqlLines.push('');

const lit = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arrLit = (arr) =>
  arr.length === 0
    ? "ARRAY[]::text[]"
    : `ARRAY[${arr.map((x) => lit(x)).join(', ')}]::text[]`;

let survivorUpdates = 0;
let deletedRows = 0;
let recipeUpdates = 0;
let invUpdates = 0;

for (const [key, rows] of dupClusters) {
  const sorted = [...rows].sort((a, b) => {
    const aMulti = (a.colors?.length || 0) > 1 ? 1 : 0;
    const bMulti = (b.colors?.length || 0) > 1 ? 1 : 0;
    if (aMulti !== bMulti) return bMulti - aMulti;
    if ((b.popularity || 0) !== (a.popularity || 0)) return (b.popularity || 0) - (a.popularity || 0);
    return (a.created_at || '').localeCompare(b.created_at || '');
  });
  const survivor = sorted[0];
  const losers = sorted.slice(1);

  // Union of colors (preserve case from first occurrence, dedupe case-insensitive)
  const colorMap = new Map();
  for (const r of rows) {
    for (const c of r.colors || []) {
      if (!colorMap.has(c.toLowerCase())) colorMap.set(c.toLowerCase(), c);
    }
  }
  const unionColors = [...colorMap.values()];

  // Union of sizes
  const sizeMap = new Map();
  for (const r of rows) {
    for (const sz of r.sizes || []) {
      if (!sizeMap.has(sz.toLowerCase())) sizeMap.set(sz.toLowerCase(), sz);
    }
  }
  const unionSizes = [...sizeMap.values()];

  // Survivor name: if all rows share a clean stem (no trailing color),
  // use the stem. Otherwise keep survivor's existing name.
  const cleanName = survivor._isExploded ? survivor._stem : survivor.name;

  sqlLines.push(`-- Cluster: ${key}  (${rows.length} rows, survivor ${survivor.id})`);
  sqlLines.push(
    `UPDATE tying_materials SET name = ${lit(cleanName)}, colors = ${arrLit(unionColors)}, sizes = ${arrLit(unionSizes)}, updated_at = now() WHERE id = ${lit(survivor.id)};`,
  );
  survivorUpdates += 1;

  if (losers.length > 0) {
    const loserIds = losers.map((l) => lit(l.id)).join(', ');
    // Re-point any recipe ingredient or inventory rows (currently zero,
    // but keep these defensive in case more land before commit).
    sqlLines.push(
      `UPDATE fly_recipe_ingredients SET material_id = ${lit(survivor.id)} WHERE material_id IN (${loserIds});`,
    );
    sqlLines.push(
      `UPDATE user_materials_inventory SET material_id = ${lit(survivor.id)} WHERE material_id IN (${loserIds});`,
    );
    sqlLines.push(`DELETE FROM tying_materials WHERE id IN (${loserIds});`);
    deletedRows += losers.length;
    recipeUpdates += 1;
    invUpdates += 1;
  }
  sqlLines.push('');
}

sqlLines.push('COMMIT;');
sqlLines.push('');
sqlLines.push(
  `-- Summary: ${survivorUpdates} survivor rows updated, ${deletedRows} exploded rows deleted.`,
);

mkdirSync('scripts/audit-output', { recursive: true });
const outPath = 'scripts/audit-output/consolidate-materials.sql';
writeFileSync(outPath, sqlLines.join('\n'));
console.log(`Wrote ${sqlLines.length} lines to ${outPath}`);
console.log(`Summary: ${survivorUpdates} survivor updates, ${deletedRows} rows to delete`);
