import { forwardRef, type ComponentType } from "react";
import { Icon, type IconProps } from "./Icon";
import { LUCIDE_TO_ICON, type LucideExportName } from "./names";

export type LucideCompatProps = Omit<IconProps, "name">;

function wrap(lucideName: LucideExportName) {
  const name = LUCIDE_TO_ICON[lucideName];
  const Cmp = forwardRef<SVGSVGElement, LucideCompatProps>(function LucideCompat(props, ref) {
    return <Icon ref={ref} name={name} {...props} />;
  });
  Cmp.displayName = lucideName;
  return Cmp;
}

export type LucideIcon = ComponentType<LucideCompatProps>;

